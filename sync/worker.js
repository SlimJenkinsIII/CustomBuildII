// The sync server: a Cloudflare Worker that keeps ONE encrypted blob per vault, so your devices can share it.
//
// What it can and can't do
//   - It stores only what the app sends: your data already encrypted on the device with your passphrase.
//     The passphrase never leaves your devices, so this server cannot read, search or change your data.
//   - A vault is found by a long random id and protected by a long random token (both made on your device).
//     Only the token's hash is stored here. Without the token nothing can be read, written or deleted.
//   - Every save needs the revision it is based on (If-Match). Two devices can't silently overwrite each other:
//     the second one is told "someone saved first" (409) and the app asks what to do.
//   - The last few revisions are kept, so a bad save can be undone from the dashboard.
//
// Storage: a Cloudflare D1 database bound as DB. Tables are created on first use.

const MAX_BODY = 6 * 1024 * 1024;          // a vault is a few hundred KB; this is a generous ceiling
const CHUNK = 900_000;                      // D1 rows are small, so a blob is stored in pieces
const KEEP = 3;                             // revisions kept
const ID_RE = /^[a-z0-9]{20,40}$/;          // ids are generated by the app
const TOKEN_RE = /^[a-z0-9]{28,64}$/;

const SCHEMA = [
  'CREATE TABLE IF NOT EXISTS vaults (id TEXT PRIMARY KEY, token_hash TEXT NOT NULL, rev INTEGER NOT NULL, chunks INTEGER NOT NULL, bytes INTEGER NOT NULL, updated_at INTEGER NOT NULL)',
  'CREATE TABLE IF NOT EXISTS chunks (id TEXT NOT NULL, rev INTEGER NOT NULL, idx INTEGER NOT NULL, body TEXT NOT NULL, PRIMARY KEY (id, rev, idx))',
];
const ready = new WeakSet();   // databases whose tables are known to exist

const sha256 = async text => [...new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text)))].map(b => b.toString(16).padStart(2, '0')).join('');
// Compares without stopping at the first difference, so timing reveals nothing.
const same = (a, b) => { if (a.length !== b.length) return false; let d = 0; for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i); return d === 0; };

function headers(env, extra = {}) {
  return {
    'access-control-allow-origin': env.ALLOWED_ORIGIN || 'https://app.millhaus.app',
    'access-control-allow-headers': 'authorization, if-match, content-type',
    'access-control-allow-methods': 'GET, PUT, DELETE, OPTIONS',
    'access-control-max-age': '86400',
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
    'referrer-policy': 'no-referrer',
    vary: 'origin',
    ...extra,
  };
}
const json = (env, status, body) => new Response(JSON.stringify(body), { status, headers: headers(env, { 'content-type': 'application/json' }) });

async function setup(db) {
  if (ready.has(db)) return;
  for (const sql of SCHEMA) await db.prepare(sql).run();
  ready.add(db);
}

export async function handle(request, env) {
  if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers: headers(env) });
  const url = new URL(request.url);
  const m = /^\/v1\/vault\/([a-z0-9]+)$/.exec(url.pathname);
  if (!m || !ID_RE.test(m[1])) return json(env, 404, { error: 'not found' });
  const id = m[1];
  const auth = /^Bearer ([a-z0-9]+)$/.exec(request.headers.get('authorization') ?? '');
  if (!auth || !TOKEN_RE.test(auth[1])) return json(env, 401, { error: 'unauthorized' });
  const hash = await sha256(auth[1]);
  const db = env.DB;
  await setup(db);
  const row = await db.prepare('SELECT token_hash, rev, chunks, updated_at FROM vaults WHERE id = ?').bind(id).first();
  if (row && !same(row.token_hash, hash)) return json(env, 401, { error: 'unauthorized' });

  if (request.method === 'GET') {
    if (!row) return json(env, 200, { exists: false });                          // not an error: a new device asks before the first save
    const parts = await db.prepare('SELECT body FROM chunks WHERE id = ? AND rev = ? ORDER BY idx').bind(id, row.rev).all();
    const list = parts.results ?? parts;
    if (list.length !== row.chunks) return json(env, 500, { error: 'incomplete' });
    return json(env, 200, { rev: row.rev, updated: row.updated_at, envelope: list.map(p => p.body).join('') });
  }

  if (request.method === 'PUT') {
    const ifMatch = request.headers.get('if-match');
    if (ifMatch === null || !/^\d+$/.test(ifMatch)) return json(env, 428, { error: 'if-match required' });
    const base = Number(ifMatch);
    if (Number(request.headers.get('content-length') ?? 0) > MAX_BODY) return json(env, 413, { error: 'too large' });
    const body = await request.text();
    if (body.length > MAX_BODY) return json(env, 413, { error: 'too large' });
    if (body.length < 20 || !/^\{[\s\S]*\}$/.test(body)) return json(env, 400, { error: 'not an envelope' });
    const current = row ? row.rev : 0;
    if (base !== current) return json(env, 409, { rev: current });
    const rev = current + 1;
    const pieces = [];
    for (let i = 0; i < body.length; i += CHUNK) pieces.push(body.slice(i, i + CHUNK));
    const now = Date.now();
    try {
      await db.batch(pieces.map((p, i) => db.prepare('INSERT INTO chunks (id, rev, idx, body) VALUES (?, ?, ?, ?)').bind(id, rev, i, p)));
    } catch { return json(env, 409, { rev: current }); }                                 // someone else saved at the same moment
    let won;
    if (row) {
      const r = await db.prepare('UPDATE vaults SET rev = ?, chunks = ?, bytes = ?, updated_at = ? WHERE id = ? AND rev = ?').bind(rev, pieces.length, body.length, now, id, current).run();
      won = (r.meta?.changes ?? r.changes ?? 0) === 1;
    } else {
      try { await db.prepare('INSERT INTO vaults (id, token_hash, rev, chunks, bytes, updated_at) VALUES (?, ?, ?, ?, ?, ?)').bind(id, hash, rev, pieces.length, body.length, now).run(); won = true; }
      catch { won = false; }
    }
    if (!won) {
      await db.prepare('DELETE FROM chunks WHERE id = ? AND rev = ?').bind(id, rev).run();
      const latest = await db.prepare('SELECT rev FROM vaults WHERE id = ?').bind(id).first();
      return json(env, 409, { rev: latest?.rev ?? current });
    }
    await db.prepare('DELETE FROM chunks WHERE id = ? AND rev <= ?').bind(id, rev - KEEP).run();
    return json(env, 200, { rev, updated: now });
  }

  if (request.method === 'DELETE') {
    if (!row) return json(env, 200, { deleted: false });
    await db.batch([db.prepare('DELETE FROM chunks WHERE id = ?').bind(id), db.prepare('DELETE FROM vaults WHERE id = ?').bind(id)]);
    return json(env, 200, { deleted: true });
  }

  return json(env, 405, { error: 'method not allowed' });
}

export default {
  async fetch(request, env) {
    try { return await handle(request, env); }
    catch { return json(env, 500, { error: 'server error' }); }
  },
};
